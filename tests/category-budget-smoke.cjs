const { chromium }=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({headless:true});
const page=await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{const Base=Date;class DemoDate extends Base{constructor(...a){if(a.length)super(...a);else super('2026-10-16T12:00:00Z')}static now(){return new Base('2026-10-16T12:00:00Z').getTime()}}window.Date=DemoDate});
try{
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'load'});
 assert.equal(await page.locator('#title').innerText(),'Budgets');
 assert.equal(await page.locator('aside button[data-page]').count(),6,'Six primary navigation choices');
 assert.equal(await page.locator('aside button.active').getAttribute('data-page'),'budgets');
 assert.equal(await page.locator('#period').inputValue(),'2026-10');
 assert.equal(await page.locator('#period option[value="all"]').count(),0,'Budget selector must use a month');
 assert.match(await page.locator('#budget-range').innerText(),/Oct 1 – Oct 31, 2026/);
 await page.locator('#period').selectOption('2026-02');
 assert.match(await page.locator('#budget-range').innerText(),/Feb 1 – Feb 28, 2026/);
 await page.locator('#period').selectOption('2026-09');
 assert.match(await page.locator('#budget-range').innerText(),/Sep 1 – Sep 30, 2026/);
 await page.locator('#period').selectOption('2026-10');
 const budget=page.locator('.budget-entry').filter({has:page.locator('summary strong:text-is("Groceries"), summary .budget-title:text-is("Groceries")')});
 assert.equal(await budget.count(),1,'Groceries budget present');
 const bar=budget.locator('.budget-progress');
 const actual=bar.locator('.actual'),forecast=bar.locator('.forecast');
 assert.ok(await actual.evaluate(e=>parseFloat(e.style.width))>0,'Actual spending visible');
 assert.ok(await forecast.evaluate(e=>parseFloat(e.style.width))>0,'Projected spending visible');
 assert.notEqual(await actual.evaluate(e=>getComputedStyle(e).backgroundColor),await forecast.evaluate(e=>getComputedStyle(e).backgroundColor),'Two bar colors');
 const cap=budget.locator('[data-inline-budget]');
 assert.ok(await cap.isVisible(),'Budget target is directly editable on the collapsed row');
 assert.match(await cap.getAttribute('class'),/editable-value/,'Underline makes editable amounts distinct');
 await cap.click();
 assert.equal(await budget.locator('.inline-money-input').count(),1,'Budget amount opens in place');
 await budget.locator('.inline-money-input').fill('500');
 await budget.locator('.inline-money-input').press('Enter');
 assert.equal(await cap.innerText(),'$500.00','Edited cap appears immediately');
 assert.equal(await budget.locator(':scope > details').evaluate(e=>e.open),false,'Changing a value does not expand the card');
 assert.equal(await page.locator('#entry').count(),0,'No budget edit dialog appears');
 const changed=await page.evaluate(()=>JSON.parse(localStorage.getItem('household-ledger-v1')));
 assert.equal(changed.predictions.monthlyBudgets.Groceries,500,'New cap persists separately from the ledger');
 await cap.click();
 await budget.locator('.inline-money-input').fill('900');
 await budget.locator('.inline-money-input').press('Escape');
 assert.equal(await cap.innerText(),'$500.00','Escape cancels an inline edit');
 await budget.locator(':scope > details > summary').click();
 assert.ok(await budget.locator('details').first().evaluate(e=>e.open),'Budget expands');
 assert.ok(await budget.locator('select[data-category]').count()>0,'Budget contains transactions');
 assert.equal(await budget.locator('button[data-budget]').count(),0,'Legacy budget dialog is removed');
 assert.match(await budget.innerText(),/Expected transactions/i);
 assert.ok(await budget.locator('.expected-tx').count()>=3,'Category shows dated expected transactions');
 await page.locator('#period').selectOption('2026-09');
 const past=page.locator('.budget-entry').filter({has:page.locator('summary .budget-title:text-is("Groceries")')});
 assert.match(await past.innerText(),/Completed month/);
 assert.equal(await past.locator('.forecast').evaluate(el=>parseFloat(el.style.width)),0,'Past month has no forward forecast');
 await page.locator('aside [data-page="insights"]').click();
 assert.equal(await page.locator('#period option[value="all"]').count(),1,'Non-budget dates remain flexible');
 assert.equal(await page.locator('[data-insight]').count(),5,'Insights has five views including Accuracy');
 const categories=page.locator('details.drill-detail');
 assert.ok(await categories.count()>2,'Categories expandable');
 await categories.first().locator('summary').click();
 assert.ok(await categories.first().evaluate(e=>e.open));
 assert.ok(await categories.first().locator('[data-category]').count()>0);
 await page.locator('[data-insight="merchants"]').click();
 const merchants=page.locator('#view details.drill-detail');
 assert.ok(await merchants.count()>5);
 const amazon=merchants.filter({has:page.locator('summary b:text-is("Amazon")')}).first();
 assert.equal(await amazon.count(),1);
 await amazon.locator('summary').click();
 assert.ok(await amazon.evaluate(e=>e.open));
 assert.ok(await amazon.locator('[data-category]').count()>0);
 await page.locator('aside [data-page="transactions"]').click();
 assert.match(await page.locator('#view').innerText(),/Transactions/i);
 assert.ok(await page.locator('#view [data-category]').count()>0);
 await page.locator('aside [data-page="settings"]').click();
 assert.equal(await page.locator('#backup').count(),1,'Read-only export remains reachable');
 assert.equal(await page.locator('#settings-import,#load-demo,#importBtn,#addBtn').count(),0,'No manual bank-ledger writing options');
 await page.locator('aside [data-page="budgets"]').click();
 await page.evaluate(()=>{const key='household-ledger-v1',d=JSON.parse(localStorage.getItem(key));d.transactions.push({id:'leap-fixture',date:'2024-02-29',merchant:'Leap Day Grocery',amount:19.90,category:'Groceries',type:'expense',account:'Checking'});localStorage.setItem(key,JSON.stringify(d))});
 await page.reload({waitUntil:'load'});
 await page.locator('#period').selectOption('2024-02');
 assert.match(await page.locator('#budget-range').innerText(),/Feb 1 – Feb 29, 2024/);
 const leap=page.locator('.budget-entry').filter({has:page.locator('.budget-title:text-is("Groceries")')});
 await leap.locator(':scope > details > summary').click();
 assert.match(await leap.innerText(),/Leap Day Grocery/);
 // Demo has the identical posted/pending budget accounting as Real.
 await page.locator('#period').selectOption('2026-10');
 const healthRow=()=>page.locator('.budget-entry[data-budget-category="Health"]');
 const healthBefore=Number((await healthRow().locator('.budget-summary-amount').innerText()).replace(/[$,]/g,''));
 await page.evaluate(()=>{
  const key='household-ledger-v1',d=JSON.parse(localStorage.getItem(key));
  d.transactions.push(
   {id:'demo-health-posted',date:'2026-10-14',merchant:'Clinic Visit',amount:42,category:'Other',type:'expense',account:'Checking',pending:false,source:{provider:'demo',verified:false}},
   {id:'demo-health-pending',date:'2026-10-15',merchant:'Lab Work',amount:18,category:'Other',type:'expense',account:'Checking',pending:true,source:{provider:'demo',verified:false}});
  localStorage.setItem(key,JSON.stringify(d));
 });
 await page.reload({waitUntil:'load'});
 await page.locator('aside [data-page=transactions]').click();
 await page.locator('#period').selectOption('2026-10');
 await page.locator('select[data-category="demo-health-posted"]').selectOption('Health');
 await page.locator('select[data-category="demo-health-pending"]').selectOption('Health');
 assert.equal(await page.locator('select[data-category="demo-health-pending"]').inputValue(),'Health');
 await page.locator('aside [data-page=budgets]').click();
 const healthAfter=Number((await healthRow().locator('.budget-summary-amount').innerText()).replace(/[$,]/g,''));
 assert.ok(Math.abs(healthAfter-healthBefore-42)<.01,'Demo Health budget counts only posted $42');
 assert.match(await healthRow().locator(':scope > details > summary').innerText(),/Pending \$18\.00 · not yet counted/);
 await healthRow().locator(':scope > details > summary').click();
 assert.equal(await healthRow().locator('.recorded-section').first().locator('select[data-category="demo-health-posted"]').count(),1);
 assert.equal(await healthRow().locator('.recorded-section').first().locator('select[data-category="demo-health-pending"]').count(),0);
 assert.equal(await healthRow().locator('.budget-pending-section select[data-category="demo-health-pending"]').count(),1);
 assert.deepEqual(errors,[],'No client-side errors');
 console.log('PASS: six-nav layout, budget period boundaries, expandable forecasts, category/merchant tabs, activity and settings');
}finally{await browser.close()}
})().catch(err=>{console.error(err);process.exit(1)});
